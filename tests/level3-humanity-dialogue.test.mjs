import assert from 'node:assert/strict';
import {OPENING_CONVERSATION,endingReflection} from '../Level3HumanityDialogue.js';
assert.equal(OPENING_CONVERSATION.length,5);
assert.equal(new Set(OPENING_CONVERSATION.map(x=>x.id)).size,5);
assert(OPENING_CONVERSATION.every(x=>!x.choices&&x.continueLabel));
assert.match(OPENING_CONVERSATION.at(-1).text,/five charges/i);
assert.match(OPENING_CONVERSATION.at(-1).text,/must kill/i);
assert.match(OPENING_CONVERSATION.at(-1).text,/shoot or cure/i);
const result=endingReflection({kills:3,saved:12});
assert.match(result,/killed 3 infected and saved 12/i);
assert.match(result,/guardian was killed/i);
assert.doesNotMatch(result,/contained|undecided|slip past/i);
assert.match(endingReflection({kills:Infinity,saved:-2}),/killed 0 infected and saved 0/i);
console.log('PASS: mandatory combat briefing, five-charge cure guidance, lethal Guardian ending and valid counts.');
